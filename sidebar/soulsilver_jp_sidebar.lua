local read32 = memory.readdwordunsigned
local read8 = memory.readbyte
local JP_SOULSILVER = 0x4A475049 -- IPGJ
local SAVE_POINTER = 0x021D1768
local DEX_MAGIC = 0xBEEFCAFE
local SAVE_ARRAY_HEADERS = 0x23014
local MAX_MAP_ID = 539

local function caught(dex, speciesID)
    local index = speciesID - 1
    local flags = read8(dex + 4 + math.floor(index / 8))
    return math.floor(flags / 2 ^ (index % 8)) % 2 == 1
end

local function currentState()
    if read32(0x02FFFE0C) ~= JP_SOULSILVER then
        return nil, "日本語版ソウルシルバーを待機中"
    end

    local save = read32(SAVE_POINTER)
    if save < 0x02000000 or save > 0x023DCCF4 or save % 4 ~= 0 then
        return nil, "ゲームデータを待機中"
    end
    local dex = save + 0x12C8
    if read32(dex) ~= DEX_MAGIC then
        return nil, "図鑑データを待機中"
    end

    local localFieldHeader = save + SAVE_ARRAY_HEADERS + 5 * 16
    local offset = read32(localFieldHeader + 8)
    if read32(localFieldHeader) ~= 5 or offset < 4 or offset >= 0x12B8 or offset % 4 ~= 0 then
        return nil, "マップデータを待機中"
    end
    local mapID = read32(save + 0x10 + offset)
    if mapID < 1 or mapID > MAX_MAP_ID then
        return nil, "現在地を取得中"
    end
    return dex, mapID
end


local previous
local function quoted(value)
    return '"' .. value:gsub('([\\"])', '\\%1') .. '"'
end

local function publish()
    local dex, mapID = currentState()
    local map = dex and maps[mapID]
    local location = map and map[1] or (dex and ("マップ #" .. mapID) or mapID)
    local groups = {}
    if map then
        for index = 2, #map do
            local group = map[index]
            local entries = { quoted(group[1]) }
            for member = 2, #group do
                local species = group[member]
                if not caught(dex, species) then
                    entries[#entries + 1] = tostring(species)
                end
            end
            if #entries > 1 then
                groups[#groups + 1] = "[" .. table.concat(entries, ",") .. "]"
            end
        end
    end
    local payload = '{"location":' .. quoted(location) ..
        ',"groups":[' .. table.concat(groups, ",") .. ']}'
    if payload ~= previous then
        print("PokemonCatcher sidebar:" .. payload)
        previous = payload
    end
end

gui.register(publish)
