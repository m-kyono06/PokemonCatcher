local DIAMOND = 0x4A414441 -- ADAJ
local PEARL = 0x4A415041 -- APAJ
local PLATINUM = 0x4A555043 -- CPUJ
local DEX_MAGIC = 0xBEEFCAFE
local DEX_ENTRY_ID = 7
local SAVE_ENTRY_SIZE = 16
local MAIN_RAM_START = 0x02000000
local MAIN_RAM_END = 0x02400000

local function caught(dex, species)
    local index = species - 1
    local flags = read8(dex + 4 + math.floor(index / 8))
    return math.floor(flags / 2 ^ (index % 8)) % 2 == 1
end

local function currentState()
    local game = read32(0x02FFFE0C)
    if game ~= DIAMOND and game ~= PEARL and game ~= PLATINUM then
        return nil, "日本語版ダイヤモンド・パール・プラチナを待機中"
    end

    local pointer, bodyOffset, tableOffset, mapOffset, maxMapID
    if game == PLATINUM then
        pointer, bodyOffset, tableOffset, mapOffset, maxMapID = 0x021BFB94, 0x14, 0x20024, 0x1294, 592
    else
        -- The Japanese launch release and later revisions move the save pointer.
        local original = read8(0x02FFFE6C) % 16 == 0xC
        pointer = original and 0x021C7234 or 0x021C7374
        bodyOffset, tableOffset, mapOffset, maxMapID = 0x214, 0x20224, 0x144C, 558
    end

    local save = read32(pointer)
    local body = save + bodyOffset
    local entry = save + tableOffset + DEX_ENTRY_ID * SAVE_ENTRY_SIZE
    if save < MAIN_RAM_START or entry + SAVE_ENTRY_SIZE > MAIN_RAM_END or save % 4 ~= 0 then
        return nil, "ゲームデータを待機中"
    end

    local dexOffset = read32(entry + 8)
    if read32(entry) ~= DEX_ENTRY_ID or dexOffset == 0 or dexOffset % 4 ~= 0 or dexOffset + 66 > 0x20000 then
        return nil, "図鑑データを待機中"
    end
    local dex = body + dexOffset
    if read32(dex) ~= DEX_MAGIC then
        return nil, "図鑑データを待機中"
    end

    local mapID = read16(save + mapOffset)
    if mapID < 1 or mapID > maxMapID then
        return nil, "現在地を取得中"
    end
    return dex, mapID, game
end

local function quoted(value)
    return '"' .. value:gsub('([\\"])', '\\%1') .. '"'
end

local previous
local function publish()
    local dex, mapID, game = currentState()
    local maps = game == PLATINUM and platinumMaps or diamondMaps
    local map = dex and maps[mapID]
    local location = map and map[1] or (dex and ("マップ #" .. mapID) or mapID)
    local groups = {}
    if map then
        local overrides = game == PEARL and pearlGroups[mapID]
        local candidates = overrides or map
        local firstGroup = overrides and 1 or 2
        for index = firstGroup, #candidates do
            local group = candidates[index]
            local entries = { quoted(group[1]) }
            for member = 2, #group do
                local species = group[member]
                entries[#entries + 1] = tostring(caught(dex, species) and -species or species)
            end
            groups[#groups + 1] = "[" .. table.concat(entries, ",") .. "]"
        end
    end
    local payload = '{"location":' .. quoted(location) ..
        ',"groups":[' .. table.concat(groups, ",") .. ']}'
    if payload ~= previous then
        print("PokemonCatcher sidebar:" .. payload)
        previous = payload
    end
end

gui.register(publish)
