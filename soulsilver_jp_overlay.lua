local function characters(value)
    return value:gmatch("[%z\1-\127\194-\244][\128-\191]*")
end

local function advance(char)
    return #char == 1 and 5 or 9
end

local function textWidth(value)
    local width = 0
    for char in characters(value) do
        width = width + advance(char)
    end
    return width
end

-- Read the bitmap as horizontal white runs once, at script load.
local glyphs = {}
for char, bitmap in pairs(bitmaps) do
    local runs = {}
    for offset = 1, #bitmap, 2 do
        local row = tonumber(bitmap:sub(offset, offset + 1), 16)
        local start
        for x = 0, 8 do
            if x < 8 and math.floor(row / 2 ^ x) % 2 == 1 then
                start = start or x
            elseif start then
                runs[#runs + 1] = { start, (offset - 1) / 2, x - 1 }
                start = nil
            end
        end
    end
    glyphs[char] = runs
end

local function drawText(x, y, value)
    for char in characters(value) do
        if char ~= " " then
            for _, run in ipairs(glyphs[char]) do
                gui.line(x + run[1], y + run[2], x + run[3], y + run[2], "white")
            end
        end
        x = x + advance(char)
    end
end

local function linesForMap(dex, mapID)
    local map = maps[mapID]
    if not map then
        return { "マップ #" .. mapID, "通常出現データなし" }
    end
    local lines = { map[1] .. "  #" .. mapID }
    local caughtByID = {}
    for groupIndex = 2, #map do
        local group = map[groupIndex]
        local prefix = group[1] .. "： "
        local line = prefix
        local count = 0
        for index = 2, #group do
            local id = group[index]
            if caughtByID[id] == nil then
                caughtByID[id] = caught(dex, id)
            end
            if not caughtByID[id] then
                local name = names[id]
                local separator = count > 0 and "、" or ""
                if textWidth(line .. separator .. name) > TEXT_WIDTH then
                    lines[#lines + 1] = line
                    line = "  " .. name
                else
                    line = line .. separator .. name
                end
                count = count + 1
            end
        end
        if count > 0 then
            lines[#lines + 1] = line
        end
    end
    if #lines == 1 then
        lines[2] = "未捕獲のポケモンはいません"
    end
    return lines
end

local function draw()
    local dex, mapOrMessage = currentState()
    local lines = dex and linesForMap(dex, mapOrMessage) or { mapOrMessage }
    if textWidth(lines[1]) > TEXT_WIDTH then
        local width, offset = 0, 0
        for char in characters(lines[1]) do
            width = width + advance(char)
            if width > TEXT_WIDTH then
                break
            end
            offset = offset + #char
        end
        local remainder = lines[1]:sub(offset + 1):gsub("^ +", "")
        table.insert(lines, 2, remainder)
        lines[1] = lines[1]:sub(1, offset)
    end
    local y = 2
    gui.box(1, y, 253, y + 4 + (#lines + 1) * 12, "#000000BB", "#FFFFFF55")
    drawText(4, y + 2, "未捕獲ポケモン（通常出現）")
    for index, line in ipairs(lines) do
        drawText(4, y + 2 + index * 12, line)
    end
end

gui.register(draw)

