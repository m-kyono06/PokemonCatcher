    end

    local save = read32(SAVE_POINTER)
    if save < 0x02000000 or save > 0x023DCCF4 or save % 4 ~= 0 then
        return nil, "Waiting for game data"
    end
    local dex = save + 0x12C8
    if read32(dex) ~= DEX_MAGIC then
        return nil, "Waiting for valid Pokedex"
    end

    local localFieldHeader = save + SAVE_ARRAY_HEADERS + 5 * 16
    local offset = read32(localFieldHeader + 8)
    if read32(localFieldHeader) ~= 5 or offset < 4 or offset >= 0x12B8 or offset % 4 ~= 0 then
        return nil, "Waiting for valid map data"
    end
    local mapID = read32(save + 0x10 + offset)
    if mapID < 1 or mapID > MAX_MAP_ID then
        return nil, "Waiting for current map"
    end
    return dex, mapID
end

local function linesForMap(dex, mapID)
    local map = maps[mapID]
    if not map then
        return { "Map #" .. mapID, "No standard encounter table" }
    end
    local lines = { map[1] .. "  #" .. mapID }
    local caughtByID = {}
    for groupIndex = 2, #map do
        local group = map[groupIndex]
        local prefix = group[1] .. ": "
        local line = prefix
        local count = 0
        for index = 2, #group do
            local id = group[index]
            if caughtByID[id] == nil then
                caughtByID[id] = caught(dex, id)
            end
            if not caughtByID[id] then
                local name = names[id]
                local separator = count > 0 and ", " or ""
                if #line + #separator + #name > COLUMNS then
                    lines[#lines + 1] = line
                    line = "  " .. name
                else
                    line = line .. separator .. name
                end
                count = count + 1
            end
        end
        if count > 0 then
            lines[#lines + 1] = line
        end
    end
    if #lines == 1 then
        lines[2] = "No uncaught standard encounters"
    end
    return lines
end

local function draw()
    local dex, mapOrMessage = currentState()
    local lines = dex and linesForMap(dex, mapOrMessage) or { mapOrMessage }
    local y = 2
    gui.box(1, y, 240, y + 4 + (#lines + 1) * 9, "#000000BB", "#FFFFFF55")
    gui.text(4, y + 2, "Uncaught - standard encounters", "white")
    for index, line in ipairs(lines) do
        gui.text(4, y + 2 + index * 9, line, "white")
    end
end

gui.register(draw)
